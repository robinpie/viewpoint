/* config.c - locate, parse and apply the user config file.
 *
 * The config lives at $XDG_CONFIG_HOME/viewpoint/viewpoint.conf, falling back
 * to ~/.config/viewpoint/viewpoint.conf when XDG_CONFIG_HOME is unset. It is an
 * optional, line-oriented "key = value" file:
 *
 *     # comments run to end of line
 *     bind   = alt+enter   new          # add or change a chord
 *     unbind = alt+f4                    # drop a default chord
 *     toggle = f12                       # the INTERPRET/PASSTHROUGH key
 *     scrollback  = 2000                 # per-window history lines
 *     scroll_step = 3                    # lines per mouse-wheel notch
 *
 * The keymap starts as a copy of the built-in defaults (input.c), which the
 * bind/unbind lines then edit. Recognized keys are dispatched in config_apply();
 * add cases there as more tunables appear. Chord and action name parsing lives
 * in input.c, next to the keymap it builds.
 */
#define _GNU_SOURCE
#include "viewpoint.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>
#include <sys/stat.h>
#include <errno.h>

bool config_path(char *buf, size_t buflen)
{
	int n;
	const char *xdg = getenv("XDG_CONFIG_HOME");
	if (xdg && *xdg) {
		n = snprintf(buf, buflen, "%s/viewpoint/viewpoint.conf", xdg);
	} else {
		const char *home = getenv("HOME");
		if (!home || !*home) {
			return false;
		}
		n = snprintf(buf, buflen, "%s/.config/viewpoint/viewpoint.conf",
			     home);
	}
	return n > 0 && (size_t)n < buflen;
}

static char *trim(char *s)
{
	while (*s && isspace((unsigned char)*s)) {
		s++;
	}
	char *end = s + strlen(s);
	while (end > s && isspace((unsigned char)end[-1])) {
		*--end = '\0';
	}
	return s;
}

/* Section markers in the on-disk file. Everything above the in-app marker is
 * the user's "manual" section (preserved verbatim on save); everything below it
 * is regenerated by config_save() from in-app/automatic changes. */
#define CFG_TOP_HDR "# viewpoint config"
#define CFG_MANUAL_HDR "# manual configuration:"
#define CFG_INAPP_HDR "# in-app/automatically set configuration:"

/* Markers are matched by prefix (after trimming) so trailing content on the
 * marker line - e.g. "# manual configuration: (your settings)" - still flags
 * the section instead of being silently swallowed into the wrong block. */
static bool is_marker(const char *line, const char *marker)
{
	return strncmp(line, marker, strlen(marker)) == 0;
}

static bool parse_hex_color(const char *s, vp_rgb *out)
{
	if (*s == '#') {
		s++;
	}
	char *end = NULL;
	unsigned long v = strtoul(s, &end, 16);
	if (end == s || *trim(end) != '\0' || v > 0xffffffUL) {
		return false;
	}
	*out = (vp_rgb)v;
	return true;
}

static bool set_color_override(VpConfig *cfg, int idx, vp_rgb color)
{
	for (int i = 0; i < cfg->n_color_overrides; i++) {
		if (cfg->color_overrides[i].field_idx == idx) {
			cfg->color_overrides[i].color = color;
			return true;
		}
	}
	if (cfg->n_color_overrides == cfg->color_cap) {
		int nc = cfg->color_cap ? cfg->color_cap * 2 : 8;
		VpColorOverride *n = realloc(cfg->color_overrides,
					    (size_t)nc * sizeof(*n));
		if (!n) {
			return false;
		}
		cfg->color_overrides = n;
		cfg->color_cap = nc;
	}
	cfg->color_overrides[cfg->n_color_overrides].field_idx = idx;
	cfg->color_overrides[cfg->n_color_overrides].color = color;
	cfg->n_color_overrides++;
	return true;
}

bool config_set_color_override(VpConfig *cfg, int idx, vp_rgb color)
{
	return set_color_override(cfg, idx, color);
}

void config_clear_color_override(VpConfig *cfg, int idx)
{
	for (int i = 0; i < cfg->n_color_overrides; i++) {
		if (cfg->color_overrides[i].field_idx == idx) {
			cfg->color_overrides[i] =
				cfg->color_overrides[--cfg->n_color_overrides];
			return;
		}
	}
}

bool config_has_color_override(const VpConfig *cfg, int idx, vp_rgb *out)
{
	for (int i = 0; i < cfg->n_color_overrides; i++) {
		if (cfg->color_overrides[i].field_idx == idx) {
			if (out) {
				*out = cfg->color_overrides[i].color;
			}
			return true;
		}
	}
	return false;
}

/* Apply one parsed key/value pair to cfg. Returns false for unknown keys or
 * malformed values. line is supplied only for diagnostics. */
static bool config_apply(VpConfig *cfg, const char *key, char *val, int line)
{
	if (strcmp(key, "bind") == 0) {
		/* value is "<chord> <action>" */
		char *sp = val;
		while (*sp && !isspace((unsigned char)*sp)) {
			sp++;
		}
		if (*sp == '\0') {
			vp_log("config: line %d: bind needs '<chord> <action>'\n",
			       line);
			return false;
		}
		*sp = '\0';
		char *action = trim(sp + 1);
		return keymap_bind(cfg, val, action);
	}
	if (strcmp(key, "unbind") == 0) {
		return keymap_unbind(cfg, val);
	}
	if (strcmp(key, "toggle") == 0) {
		return keymap_set_toggle(cfg, val);
	}
	if (strcmp(key, "scrollback") == 0) {
		char *end = NULL;
		long n = strtol(val, &end, 10);
		if (end == val || *trim(end) != '\0' || n < 0 ||
		    n > VP_SCROLLBACK_LIMIT) {
			vp_log("config: line %d: scrollback needs 0..%d\n",
			       line, VP_SCROLLBACK_LIMIT);
			return false;
		}
		cfg->scrollback_max = (int)n;
		return true;
	}
	if (strcmp(key, "scroll_step") == 0) {
		char *end = NULL;
		long n = strtol(val, &end, 10);
		if (end == val || *trim(end) != '\0' || n < 1 ||
		    n > VP_SCROLL_STEP_MAX) {
			vp_log("config: line %d: scroll_step needs 1..%d\n",
			       line, VP_SCROLL_STEP_MAX);
			return false;
		}
		cfg->scroll_step = (int)n;
		return true;
	}
	if (strcmp(key, "icon") == 0) {
		/* value is "<name> <x> <y>" - a desktop launcher icon's top-left cell */
		char name[16];
		int x, y;
		if (sscanf(val, "%15s %d %d", name, &x, &y) != 3) {
			vp_log("config: line %d: icon needs '<name> <x> <y>'\n",
			       line);
			return false;
		}
		if (strcmp(name, "settings") == 0) {
			cfg->settings_icon_x = x;
			cfg->settings_icon_y = y;
		} else if (strcmp(name, "exit") == 0) {
			cfg->exit_icon_x = x;
			cfg->exit_icon_y = y;
		} else {
			vp_log("config: line %d: unknown icon '%s'\n", line,
			       name);
			return false;
		}
		return true;
	}
	if (strcmp(key, "theme") == 0) {
		if (!vp_theme_builtin(val)) {
			vp_log("config: line %d: unknown theme '%s'\n", line,
			       val);
			return false;
		}
		free(cfg->theme_name);
		cfg->theme_name = strdup(val);
		return true;
	}
	if (strcmp(key, "background") == 0) {
		/* "solid" | "pattern <glyph>" | "image <path>" */
		char *sp = val;
		while (*sp && !isspace((unsigned char)*sp)) {
			sp++;
		}
		char *arg = NULL;
		if (*sp) {
			*sp = '\0';
			arg = trim(sp + 1);
		}
		if (strcmp(val, "solid") == 0) {
			cfg->bg_mode = BG_SOLID;
		} else if (strcmp(val, "pattern") == 0) {
			cfg->bg_mode = BG_PATTERN;
			if (arg && *arg) {
				free(cfg->bg_glyph);
				cfg->bg_glyph = strdup(arg);
			}
		} else if (strcmp(val, "image") == 0) {
			if (!arg || !*arg) {
				vp_log("config: line %d: background image needs a path\n",
				       line);
				return false;
			}
			cfg->bg_mode = BG_IMAGE;
			free(cfg->bg_image_path);
			cfg->bg_image_path = strdup(arg);
		} else {
			vp_log("config: line %d: background needs solid|pattern|image\n",
			       line);
			return false;
		}
		return true;
	}
	if (strcmp(key, "bg_fit") == 0) {
		if (strcmp(val, "stretch") == 0) {
			cfg->bg_fit = FIT_STRETCH;
		} else if (strcmp(val, "scale") == 0) {
			cfg->bg_fit = FIT_SCALE;
		} else if (strcmp(val, "center") == 0) {
			cfg->bg_fit = FIT_CENTER;
		} else if (strcmp(val, "tile") == 0) {
			cfg->bg_fit = FIT_TILE;
		} else {
			vp_log("config: line %d: bg_fit needs stretch|scale|center|tile\n",
			       line);
			return false;
		}
		return true;
	}
	if (strcmp(key, "keep_customizations") == 0) {
		if (strcmp(val, "true") == 0 || strcmp(val, "1") == 0 ||
		    strcmp(val, "yes") == 0) {
			cfg->keep_customizations = true;
		} else if (strcmp(val, "false") == 0 || strcmp(val, "0") == 0 ||
			   strcmp(val, "no") == 0) {
			cfg->keep_customizations = false;
		} else {
			vp_log("config: line %d: keep_customizations needs true/false\n",
			       line);
			return false;
		}
		return true;
	}
	if (strcmp(key, "color") == 0) {
		/* "<element> <hex>" */
		char name[32];
		char hex[16];
		if (sscanf(val, "%31s %15s", name, hex) != 2) {
			vp_log("config: line %d: color needs '<element> <hex>'\n",
			       line);
			return false;
		}
		int idx = vp_theme_field_index(name);
		if (idx < 0) {
			vp_log("config: line %d: unknown color element '%s'\n",
			       line, name);
			return false;
		}
		vp_rgb c;
		if (!parse_hex_color(hex, &c)) {
			vp_log("config: line %d: bad color hex '%s'\n", line,
			       hex);
			return false;
		}
		return set_color_override(cfg, idx, c);
	}
	vp_log("config: line %d: unknown key '%s'\n", line, key);
	return false;
}

static void config_apply_line(VpConfig *cfg, char *buf, int line)
{
	char *s = trim(buf);
	if (*s == '\0' || *s == '#') {
		return;
	}
	char *eq = strchr(s, '=');
	if (!eq) {
		vp_log("config: line %d: expected 'key = value', got '%s'\n",
		       line, s);
		return;
	}
	*eq = '\0';
	char *key = trim(s);
	char *val = trim(eq + 1);
	config_apply(cfg, key, val, line);
}

static char *buf_append(char *b, size_t *len, size_t *cap, const char *s)
{
	size_t add = strlen(s);
	if (*len + add + 1 > *cap) {
		size_t nc = *cap ? *cap * 2 : 256;
		while (nc < *len + add + 1) {
			nc *= 2;
		}
		char *n = realloc(b, nc);
		if (!n) {
			return b; /* drop the line rather than crash; best-effort capture */
		}
		b = n;
		*cap = nc;
	}
	memcpy(b + *len, s, add);
	*len += add;
	b[*len] = '\0';
	return b;
}

static void config_apply_text(VpConfig *cfg, const char *text)
{
	if (!text) {
		return;
	}
	int line = 0;
	char lb[1024];
	for (const char *p = text; *p;) {
		const char *nl = strchr(p, '\n');
		size_t len = nl ? (size_t)(nl - p) : strlen(p);
		if (len >= sizeof(lb)) {
			len = sizeof(lb) - 1;
		}
		memcpy(lb, p, len);
		lb[len] = '\0';
		config_apply_line(cfg, lb, ++line);
		if (!nl) {
			break;
		}
		p = nl + 1;
	}
}

void config_defaults(VpConfig *cfg)
{
	memset(cfg, 0, sizeof(*cfg));
	keymap_load_defaults(cfg);
	/* -1 = "unset": use each icon's built-in default placement. */
	cfg->settings_icon_y = cfg->settings_icon_x = -1;
	cfg->exit_icon_y = cfg->exit_icon_x = -1;
	cfg->scrollback_max = VP_SCROLLBACK_MAX;
	cfg->scroll_step = VP_SCROLL_STEP;
	cfg->theme_name = NULL;
	cfg->bg_mode = -1;
	cfg->bg_fit = FIT_STRETCH;
	cfg->bg_glyph = NULL;
	cfg->bg_image_path = NULL;
	cfg->keep_customizations = false;
	cfg->color_overrides = NULL;
	cfg->n_color_overrides = cfg->color_cap = 0;
}

void config_free(VpConfig *cfg)
{
	free(cfg->keymap);
	cfg->keymap = NULL;
	cfg->nkeys = 0;
	cfg->keycap = 0;
	free(cfg->manual_text);
	cfg->manual_text = NULL;
	free(cfg->theme_name);
	cfg->theme_name = NULL;
	free(cfg->bg_glyph);
	cfg->bg_glyph = NULL;
	free(cfg->bg_image_path);
	cfg->bg_image_path = NULL;
	free(cfg->color_overrides);
	cfg->color_overrides = NULL;
	cfg->n_color_overrides = cfg->color_cap = 0;
}

/* Create each directory along `path` (which names a file). Like `mkdir -p` on
 * the dirname. Best-effort: existing dirs are fine, other errors are ignored
 * here and surface as the fopen failure in config_save. */
static void mkdir_parents(const char *path)
{
	char tmp[1024];
	if (snprintf(tmp, sizeof(tmp), "%s", path) >= (int)sizeof(tmp)) {
		return;
	}
	for (char *p = tmp + 1; *p; p++) {
		if (*p == '/') {
			*p = '\0';
			if (mkdir(tmp, 0755) != 0 && errno != EEXIST) {
				/* keep going; the final fopen reports the real problem */
			}
			*p = '/';
		}
	}
}

static int chord_action(const VpConfig *cfg, uint32_t id, unsigned mods)
{
	for (int i = 0; i < cfg->nkeys; i++) {
		if (cfg->keymap[i].id == id && cfg->keymap[i].mods == mods) {
			return (int)cfg->keymap[i].act;
		}
	}
	return -1;
}

